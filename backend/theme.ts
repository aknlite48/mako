let currentThemeId = THEMES[0].id;

/** The id of the currently applied theme. */
export function getThemeId(): string {
	return currentThemeId;
}

function applyVars(theme: Theme) {
	const root = document.documentElement;
	Object.keys(FONT_VARIABLES).forEach((name) => {
		root.style.setProperty(name, FONT_VARIABLES[name]);
	});
	Object.keys(theme.vars).forEach((name) => {
		root.style.setProperty(name, theme.vars[name]);
	});
}

/** Apply & persist the theme with the given id. */
export function setTheme(id: string) {
	const theme = THEMES.find((t) => t.id === id);
	if (theme === undefined) return;
	currentThemeId = theme.id;
	applyVars(theme);
	// Listeners that cannot use var() references (e.g. xterm themes) re-read
	// the computed variables on this event.
	window.dispatchEvent(new CustomEvent('ggd-theme-changed'));
	try {
		localStorage.setItem(THEME_KEY, theme.id);
	} catch (_) { }
}

/**
 * Apply the persisted (or default) theme: inline CSS variables on <html>,
 * plus the body color/background/font that a VS Code Webview would normally
 * inherit.
 */
export function applyTheme() {
	const stored = localStorage.getItem(THEME_KEY);
	const theme = THEMES.find((t) => t.id === stored) || THEMES[0];
	currentThemeId = theme.id;
	applyVars(theme);

	// Replicate the default VS Code Webview body styling that main.css relies on
	document.body.style.color = 'var(--vscode-editor-foreground)';
	document.body.style.backgroundColor = 'var(--vscode-editor-background)';
	document.body.style.fontFamily = 'var(--vscode-font-family)';
	document.body.style.fontSize = 'var(--vscode-font-size)';
	document.body.style.fontWeight = 'var(--vscode-font-weight)';
}
